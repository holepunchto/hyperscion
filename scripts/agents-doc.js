// Bundles the agent instructions into the binary: `bare-build` packs only JavaScript, and an
// agent on a machine with just `hs` installed can't read docs/. Writes lib/agents-doc.js from
// docs/BRIEF.md (what `hs agents` prints) and the playbooks (`hs agents --full`).
//   node scripts/agents-doc.js     after editing any of them (test/agents.js checks it's current)
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const read = (f) => fs.readFileSync(path.join(ROOT, 'docs', f), 'utf8')

function render() {
  const docs = {
    brief: read('BRIEF.md'),
    full: read('AGENTS-min.md'),
    plain: read('AGENTS-plain.md')
  }
  return (
    '// Generated by scripts/agents-doc.js from docs/BRIEF.md, docs/AGENTS-min.md and\n' +
    '// docs/AGENTS-plain.md: edit those and run `node scripts/agents-doc.js`.\n' +
    'module.exports = ' +
    JSON.stringify(docs, null, 2) +
    '\n'
  )
}

module.exports = render

if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'lib', 'agents-doc.js'), render())
  console.log('wrote lib/agents-doc.js')
}
